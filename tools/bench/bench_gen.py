"""Gera dois projetos sinteticos equivalentes, um por estrategia de tipagem.

Os dois recebem a MESMA superficie de tipo compartilhada (CoreTypes, no
espirito do lync/Promise/Signal/Tools do V2). O que muda e como ela chega no
`self` de cada modulo:

  estilo v2  - o Watcher reimporta os aliases em CADA arquivo gerado e expande
               o self inteiro por modulo, com a union de Import crescendo com N
  estilo v3  - a folha declara so os metodos proprios; SelfOf enxerta
               Dependencies e a base compartilhada referencia CoreTypes uma vez
"""
import os, shutil, sys

ALIASES = [
    "callbackZone", "Child", "DataKeyPayload", "DataTemplate", "DataTemplateKey",
    "GlobalClock", "LyncConnection", "LyncPacketStats", "Mode", "Network",
    "NetworkTarget", "OnCancel", "PlayerZoneConfig", "PromiseAPI", "PromiseLike",
    "PromiseStatus", "PropertyTable", "R6", "Reject", "Scope", "SignalAPI",
    "SignalConnection", "SpecialKey", "TickRate", "Tools", "Type",
]
GENERIC = ["Executor", "LyncPacket", "Promise", "Resolve", "Value"]


def core_types() -> str:
    out = ["--!strict", "-- superficie compartilhada, igual nos dois estilos"]
    for a in ALIASES:
        out.append("export type %s = { field%s: string }" % (a, a))
    for g in GENERIC:
        out.append("export type %s<T> = { value: T }" % g)
    out.append("export type LyncQuery<Req, Resp> = { req: Req, resp: Resp }")
    out.append("export type Signal<T...> = { fire: (T...) -> () }")
    out.append("return {}")
    return "\n".join(out) + "\n"


def v2_module(i: int, n: int) -> str:
    """Espelha o formato real que o Watcher emite (ver ProfileController.luau)."""
    nome = "Mod%d" % i
    out = ["--!strict", "", "-- AUTO-GENERATED BY MODUX TOOLING - DO NOT EDIT THIS BLOCK", "",
           'local CoreTypes = require("./CoreTypes")']
    for a in ALIASES:
        out.append("type %s = CoreTypes.%s" % (a, a))
    for g in GENERIC:
        out.append("type %s<T> = CoreTypes.%s<T>" % (g, g))
    out.append("type LyncQuery<Req, Resp> = CoreTypes.LyncQuery<Req, Resp>")
    out.append("type Signal<T...> = CoreTypes.Signal<T...>")
    # a union de Import cresce com N: e isso que o Watcher gera de verdade
    union = " | ".join('"Mod%d"' % k for k in range(n))
    out += [
        "--> CONTROLLER",
        "export type %s = {" % nome,
        "\tID: string,",
        "\tType: Type,",
        "\tImport: (self: %s, id: %s, scopeKey: string?) -> %s," % (nome, union, nome),
        "\tExtend: (self: %s, id: string) -> %s," % (nome, nome),
        "\tOnInit: (self: %s, cb: (self: %s) -> ()) -> %s," % (nome, nome, nome),
        "\tOnStart: (self: %s, cb: (self: %s) -> ()) -> %s," % (nome, nome, nome),
        "\tOnTick: (self: %s, cb: (self: %s, dt: number) -> (), rate: number) -> %s," % (nome, nome, nome),
        "\tOnDestroy: (self: %s, cb: (self: %s) -> ()) -> %s," % (nome, nome, nome),
        "\tCleanup: <T>(self: any, task: T) -> T,",
        "\tNetwork: Network,",
        "\tPromise: PromiseAPI,",
        "\tGlobalClock: GlobalClock,",
        "\tSignal: SignalAPI,",
        "\tTools: Tools,",
        "\tAttributes: { [string]: any },",
        "\tDoWork: (self: %s, amount: number) -> ()," % nome,
        "\tReset: (self: %s) -> ()," % nome,
        "}", "", "-- END AUTO-GENERATED", "", "return {}",
    ]
    return "\n".join(out) + "\n"


def build_v2(d: str, n: int) -> None:
    os.makedirs(d)
    open(os.path.join(d, "CoreTypes.luau"), "w", encoding="utf-8").write(core_types())
    for i in range(n):
        open(os.path.join(d, "Mod%dTypes.luau" % i), "w", encoding="utf-8").write(v2_module(i, n))
    # Types.luau agregador: o Watcher gera um que requer TODOS os modulos e
    # reexporta os aliases (ver src/shared/Modux/Types.luau do V2 real)
    agg = ['--!strict', '-- AUTO-GENERATED BY MODUX TOOLING',
           'local CoreTypes = require("./CoreTypes")']
    for i in range(n):
        agg.append('local Mod%dModule = require("./Mod%dTypes")' % (i, i))
    agg.append('--> COMPATIBILITY TYPE EXPORTS')
    for a in ALIASES:
        agg.append('export type %s = CoreTypes.%s' % (a, a))
    for g in GENERIC:
        agg.append('export type %s<T> = CoreTypes.%s<T>' % (g, g))
    for i in range(n):
        agg.append('export type Mod%d = Mod%dModule.Mod%d' % (i, i, i))
    agg.append('return {}')
    open(os.path.join(d, 'Types.luau'), 'w', encoding='utf-8').write(chr(10).join(agg) + chr(10))

    open(os.path.join(d, 'Framework.luau'), 'w', encoding='utf-8').write(
        '--!strict' + chr(10) + 'local T = require("./Types")' + chr(10) +
        'local M = {}' + chr(10) +
        'function M.Controller(id: string): T.Mod0' + chr(10) +
        chr(9) + 'return (nil :: any)' + chr(10) + 'end' + chr(10) + 'return M' + chr(10))
    open(os.path.join(d, 'Body.luau'), 'w', encoding='utf-8').write(
        '--!strict' + chr(10) + 'local M = require("./Framework")' + chr(10) +
        'local C = M.Controller("Mod0")' + chr(10) +
        'C:OnInit(function(self)' + chr(10) +
        chr(9) + 'self:DoWork(1)' + chr(10) + chr(9) + 'self:Reset()' + chr(10) +
        chr(9) + 'local _ = self.Network' + chr(10) + 'end)' + chr(10) + 'return C' + chr(10))


def build_v3(d: str, n: int) -> None:
    os.makedirs(d)
    open(os.path.join(d, "CoreTypes.luau"), "w", encoding="utf-8").write(core_types())
    shutil.copy("src/Types/shared/SelfOf.luau", os.path.join(d, "SelfOf.luau"))
    for i in range(n):
        open(os.path.join(d, "Mod%dType.luau" % i), "w", encoding="utf-8").write(
            "--!strict\nexport type Public = {\n"
            "\tDoWork: (self: Public, amount: number) -> (),\n"
            "\tReset: (self: Public) -> (),\n}\nreturn {}\n")
    man = ["--!strict", 'local SelfOf = require("./SelfOf")']
    for i in range(n):
        man.append('local Mod%d = require("./Mod%dType")' % (i, i))
    man.append("export type AllControllers = {")
    for i in range(n):
        man.append("\tMod%d: SelfOf.Build<Mod%d.Public, { Mod%d: Mod%d.Public }>," % (i, i, (i + 1) % n, (i + 1) % n))
    man += ["}", "return {}"]
    open(os.path.join(d, "Manifest.luau"), "w", encoding="utf-8").write("\n".join(man) + "\n")
    # a superficie compartilhada entra UMA vez, na base alcancada por __index
    open(os.path.join(d, "Framework.luau"), "w", encoding="utf-8").write(
        '--!strict\nlocal Manifest = require("./Manifest")\nlocal CoreTypes = require("./CoreTypes")\n'
        "export type ControllerKey = keyof<Manifest.AllControllers>\n"
        "export type ControllerSelf<ID> = index<Manifest.AllControllers, ID>\n"
        "export type ControllerBase<ID> = {\n"
        "\tID: string,\n\tType: CoreTypes.Type,\n"
        "\tNetwork: CoreTypes.Network,\n\tPromise: CoreTypes.PromiseAPI,\n"
        "\tGlobalClock: CoreTypes.GlobalClock,\n\tSignal: CoreTypes.SignalAPI,\n"
        "\tTools: CoreTypes.Tools,\n\tAttributes: { [string]: any },\n"
        "\tCleanup: <T>(self: any, task: T) -> T,\n"
        "\tOnInit: (self: any, cb: (self: ControllerSelf<ID>) -> ()) -> (),\n"
        "\tOnStart: (self: any, cb: (self: ControllerSelf<ID>) -> ()) -> (),\n"
        "\tOnTick: (self: any, cb: (self: ControllerSelf<ID>, dt: number) -> (), rate: number) -> (),\n}\n"
        "export type ControllerReturn<ID> = setmetatable<ControllerSelf<ID>, { __index: ControllerBase<ID> }>\n"
        "local M = {}\n"
        "function M.Controller<ID, P>(id: ID & ControllerKey, props: P?): ControllerReturn<ID>\n"
        "\treturn (nil :: any)\nend\nreturn M\n")
    open(os.path.join(d, "Body.luau"), "w", encoding="utf-8").write(
        '--!strict\nlocal M = require("./Framework")\nconst C = M.Controller("Mod0")\n'
        "C:OnInit(function(self)\n"
        "\tself:DoWork(1)\n\tself:Reset()\nend)\nreturn C\n")


if __name__ == "__main__":
    base = sys.argv[1]
    sizes = [int(x) for x in sys.argv[2:]]
    shutil.rmtree(base, ignore_errors=True)
    for n in sizes:
        build_v2(os.path.join(base, "v2-n%d" % n), n)
        build_v3(os.path.join(base, "v3-n%d" % n), n)
        print("N=%d ok" % n)
